nilai = 75

# Percabangan
if nilai >= 80:
    print("Nilai: A")
elif nilai >= 70:
    print("Nilai: B")
else:
    print("Nilai: C")

# Perulangan for
print("\nPerulangan for:")
for i in range(1, 6):
    print("Angka", i)

# Perulangan while
print("\nPerulangan while:")
hitung = 1
while hitung <= 5:
    print("Hitung", hitung)
    hitung += 1
